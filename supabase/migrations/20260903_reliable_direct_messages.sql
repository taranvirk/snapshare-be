-- Reliable one-to-one messaging for Snapshare.
-- Run this once in the SQL editor of the SAME Supabase project used by the frontend.
-- The migration preserves legacy public.direct_messages rows and then revokes client access
-- to that insecure table. It is safe to rerun.

begin;

create extension if not exists pgcrypto;

create table if not exists public.conversations (
    id uuid primary key default gen_random_uuid(),
    user_one_id uuid not null references auth.users(id) on delete cascade,
    user_two_id uuid not null references auth.users(id) on delete cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    last_message_at timestamptz,
    last_message_preview text,
    last_sender_id uuid references auth.users(id) on delete set null,
    constraint conversations_distinct_users check (user_one_id <> user_two_id),
    constraint conversations_canonical_order check (user_one_id < user_two_id),
    constraint conversations_unique_pair unique (user_one_id, user_two_id)
);

create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    conversation_id uuid not null references public.conversations(id) on delete cascade,
    sender_id uuid not null references auth.users(id) on delete cascade,
    recipient_id uuid not null references auth.users(id) on delete cascade,
    body text not null,
    client_message_id uuid not null default gen_random_uuid(),
    legacy_message_id bigint unique,
    created_at timestamptz not null default now(),
    constraint messages_distinct_users check (sender_id <> recipient_id),
    constraint messages_nonempty_body check (char_length(btrim(body)) > 0),
    constraint messages_unique_client_id unique (client_message_id)
);

create index if not exists conversations_user_one_recent_idx
    on public.conversations (user_one_id, last_message_at desc nulls last, created_at desc);
create index if not exists conversations_user_two_recent_idx
    on public.conversations (user_two_id, last_message_at desc nulls last, created_at desc);
create index if not exists messages_conversation_chronological_idx
    on public.messages (conversation_id, created_at, id);
create index if not exists messages_recipient_recent_idx
    on public.messages (recipient_id, created_at desc);
create index if not exists messages_sender_recent_idx
    on public.messages (sender_id, created_at desc);

create or replace function public.validate_direct_message_participants()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
    selected_conversation public.conversations%rowtype;
begin
    select * into selected_conversation
    from public.conversations
    where id = new.conversation_id;

    if not found then
        raise exception 'Conversation not found';
    end if;

    if not (
        (new.sender_id = selected_conversation.user_one_id and new.recipient_id = selected_conversation.user_two_id)
        or
        (new.sender_id = selected_conversation.user_two_id and new.recipient_id = selected_conversation.user_one_id)
    ) then
        raise exception 'Sender and recipient must be the conversation participants';
    end if;

    return new;
end;
$$;

drop trigger if exists validate_direct_message_participants on public.messages;
create trigger validate_direct_message_participants
before insert or update on public.messages
for each row execute function public.validate_direct_message_participants();

create or replace function public.touch_conversation_after_message()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    update public.conversations
    set updated_at = new.created_at,
        last_message_at = new.created_at,
        last_message_preview = left(new.body, 160),
        last_sender_id = new.sender_id
    where id = new.conversation_id;
    return new;
end;
$$;

drop trigger if exists touch_conversation_after_message on public.messages;
create trigger touch_conversation_after_message
after insert on public.messages
for each row execute function public.touch_conversation_after_message();

create or replace function public.get_or_create_conversation(other_user_id uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
    current_user_id uuid := auth.uid();
    first_user_id uuid;
    second_user_id uuid;
    conversation_id uuid;
begin
    if current_user_id is null then
        raise exception 'Authentication required';
    end if;
    if other_user_id is null or other_user_id = current_user_id then
        raise exception 'A conversation requires two different users';
    end if;
    if not exists (select 1 from auth.users where id = other_user_id) then
        raise exception 'Recipient not found';
    end if;

    first_user_id := least(current_user_id, other_user_id);
    second_user_id := greatest(current_user_id, other_user_id);

    insert into public.conversations (user_one_id, user_two_id)
    values (first_user_id, second_user_id)
    on conflict (user_one_id, user_two_id)
    do update set user_one_id = excluded.user_one_id
    returning id into conversation_id;

    return conversation_id;
end;
$$;

-- Preserve every valid legacy message and collapse both user directions into one conversation.
do $$
begin
    if to_regclass('public.direct_messages') is not null then
        execute $migration$
            insert into public.conversations (user_one_id, user_two_id, created_at)
            select
                least(dm."sendingUserId"::uuid, dm."recievingUserId"::uuid),
                greatest(dm."sendingUserId"::uuid, dm."recievingUserId"::uuid),
                min(coalesce(dm.created_at, now()))
            from public.direct_messages dm
            join auth.users sender on sender.id = dm."sendingUserId"::uuid
            join auth.users recipient on recipient.id = dm."recievingUserId"::uuid
            where dm."sendingUserId" is not null
              and dm."recievingUserId" is not null
              and dm."sendingUserId" <> dm."recievingUserId"
            group by 1, 2
            on conflict (user_one_id, user_two_id) do nothing
        $migration$;

        execute $migration$
            insert into public.messages (
                conversation_id,
                sender_id,
                recipient_id,
                body,
                legacy_message_id,
                created_at
            )
            select
                conversation.id,
                dm."sendingUserId"::uuid,
                dm."recievingUserId"::uuid,
                dm.message,
                dm.message_id::bigint,
                coalesce(dm.created_at, now())
            from public.direct_messages dm
            join public.conversations conversation
              on conversation.user_one_id = least(dm."sendingUserId"::uuid, dm."recievingUserId"::uuid)
             and conversation.user_two_id = greatest(dm."sendingUserId"::uuid, dm."recievingUserId"::uuid)
            where dm.message is not null
              and char_length(btrim(dm.message)) > 0
            on conflict (legacy_message_id) do nothing
        $migration$;

        execute 'alter table public.direct_messages enable row level security';
        execute 'revoke all on table public.direct_messages from anon, authenticated';
        comment on table public.direct_messages is
            'Legacy Snapshare message archive. Data was migrated to public.messages; client access is intentionally revoked.';
    end if;
end;
$$;

-- Trigger execution order is not guaranteed during bulk migration, so explicitly
-- derive every conversation preview from its newest persisted message.
update public.conversations conversation
set updated_at = greatest(conversation.updated_at, latest.created_at),
    last_message_at = latest.created_at,
    last_message_preview = left(latest.body, 160),
    last_sender_id = latest.sender_id
from (
    select distinct on (conversation_id)
        conversation_id,
        sender_id,
        body,
        created_at
    from public.messages
    order by conversation_id, created_at desc, id desc
) latest
where conversation.id = latest.conversation_id;

alter table public.conversations enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Participants can view conversations" on public.conversations;
create policy "Participants can view conversations"
on public.conversations for select
to authenticated
using (auth.uid() = user_one_id or auth.uid() = user_two_id);

drop policy if exists "Participants can view messages" on public.messages;
create policy "Participants can view messages"
on public.messages for select
to authenticated
using (
    exists (
        select 1 from public.conversations conversation
        where conversation.id = messages.conversation_id
          and (auth.uid() = conversation.user_one_id or auth.uid() = conversation.user_two_id)
    )
);

drop policy if exists "Participants can send messages" on public.messages;
create policy "Participants can send messages"
on public.messages for insert
to authenticated
with check (
    auth.uid() = sender_id
    and exists (
        select 1 from public.conversations conversation
        where conversation.id = messages.conversation_id
          and (
              (sender_id = conversation.user_one_id and recipient_id = conversation.user_two_id)
              or
              (sender_id = conversation.user_two_id and recipient_id = conversation.user_one_id)
          )
    )
);

revoke all on table public.conversations from anon, authenticated;
revoke all on table public.messages from anon, authenticated;
grant select on table public.conversations to authenticated;
grant select, insert on table public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

revoke all on function public.get_or_create_conversation(uuid) from public, anon;
grant execute on function public.get_or_create_conversation(uuid) to authenticated;

do $$
begin
    if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
        if not exists (
            select 1 from pg_publication_tables
            where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages'
        ) then
            execute 'alter publication supabase_realtime add table public.messages';
        end if;
    end if;
end;
$$;

commit;
